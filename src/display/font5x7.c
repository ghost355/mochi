static void draw_glyph(int x, int y, const uint8_t *g, int scale)
{
    if (scale < 1) scale = 1;

    for (int col = 0; col < FONT_W; col++) {
        uint8_t bits = g[col];
        for (int row = 0; row < FONT_H; row++) {
            if (!(bits & (1u << row))) continue;

            int px = x + col * scale;
            int py = y + row * scale;
            if (scale == 1) {
                sh1106_set_pixel(px, py, true);
            } else {
                for (int dy = 0; dy < scale; dy++)
                    for (int dx = 0; dx < scale; dx++)
                        sh1106_set_pixel(px + dx, py + dy, true);
            }
        }
    }
}

/* Decode one UTF-8 codepoint. Returns codepoint and advances *s. */
static uint32_t utf8_next(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t cp;
    int extra;

    if (p[0] < 0x80)            { cp = p[0];        extra = 0; }
    else if ((p[0] & 0xE0) == 0xC0) { cp = p[0] & 0x1F; extra = 1; }
    else if ((p[0] & 0xF0) == 0xE0) { cp = p[0] & 0x0F; extra = 2; }
    else if ((p[0] & 0xF8) == 0xF0) { cp = p[0] & 0x07; extra = 3; }
    else                        { *s += 1; return 0xFFFD; }

    for (int i = 1; i <= extra; i++) {
        if ((p[i] & 0xC0) != 0x80) { *s += i; return 0xFFFD; }
        cp = (cp << 6) | (p[i] & 0x3F);
    }
    *s += 1 + extra;
    return cp;
}

/* Map a codepoint to a glyph table, or NULL if not representable. */
static const uint8_t *glyph_for(uint32_t cp)
{
    if (cp >= 0x20 && cp <= 0x7E) return font_ascii[cp - 0x20];
    if (cp >= 0x410 && cp <= 0x42F) return font_cyr[cp - 0x410]; /* А..Я */
    if (cp == 0x401)               return font_cyr[32];          /* Ё */
    if (cp >= 0x430 && cp <= 0x44F) return font_cyr[cp - 0x430]; /* а..я */
    if (cp == 0x451)               return font_cyr[32];          /* ё */
    if (cp == 0xA0)                return font_ascii[0];         /* NBSP */
    return font_ascii['?' - 0x20];
}

void font_draw_char(int x, int y, char c, int scale)
{
    const uint8_t *g = glyph_for((uint8_t)c);
    if (g) draw_glyph(x, y, g, scale);
}

void font_draw_str(int x, int y, const char *s, int scale)
{
    font_draw_str_ex(x, y, s, scale, 0);
}

void font_draw_str_ex(int x, int y, const char *s, int scale, int spacing)
{
    if (!s) return;
    if (scale < 1) scale = 1;

    int cx = x;
    while (*s) {
        uint32_t cp = utf8_next(&s);
        draw_glyph(cx, y, glyph_for(cp), scale);
        cx += (FONT_ADVANCE + spacing) * scale;
    }
}

int font_str_width(const char *s, int scale)
{
    return font_str_width_ex(s, scale, 0);
}

int font_str_width_ex(const char *s, int scale, int spacing)
{
    if (!s) return 0;
    if (scale < 1) scale = 1;

    int n = 0;
    while (*s) { (void)utf8_next(&s); n++; }
    return n * (FONT_ADVANCE + spacing) * scale;
}

const char *font5x7_cyr_order(void)
{
    return font_cyr_order;
}
